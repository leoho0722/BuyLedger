import SwiftUI

/// 設計系統共用間距
enum BLSpacing {

    // MARK: - Properties

    /// 最小間距
    static let extraSmall: CGFloat = 4

    /// 小間距
    static let small: CGFloat = 8

    /// 中間距
    static let medium: CGFloat = 12

    /// 大間距
    static let large: CGFloat = 16

    /// 特大間距
    static let extraLarge: CGFloat = 24

    /// 區段之間的標準間距
    static let section: CGFloat = 32
}
